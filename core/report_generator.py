"""
HashProof AI — Forensic Report Generation Engine.

Produces structured, schema-compliant JSON examination records and professional,
print-ready HTML/PDF forensic report summaries with technical observations,
chain-of-custody hashes, and formal evidentiary disclaimers.
"""

import json
from datetime import datetime, timezone
from typing import Dict, Any, Optional


def build_examination_record(
    examination_id: str,
    filename: str,
    file_size_bytes: int,
    file_size_readable: str,
    file_hash: str,
    detected_format: str,
    metadata_results: Dict[str, Any],
    hashing_results: Optional[Dict[str, Any]] = None,
    manipulation_results: Optional[Dict[str, Any]] = None,
    ai_results: Optional[Dict[str, Any]] = None,
    provenance_results: Optional[Dict[str, Any]] = None,
    comparison_results: Optional[Dict[str, Any]] = None,
    examiner_name: Optional[str] = None,
    case_reference: Optional[str] = None,
    examiner_notes: Optional[str] = None,
) -> Dict[str, Any]:
    """Assemble a comprehensive, structured forensic examination record."""
    now_utc = datetime.now(timezone.utc).isoformat()

    findings = []
    limitations = [
        "A SHA-256 hash confirms byte integrity relative to a trusted reference; it does not verify real-world authenticity or authorship.",
        "Image metadata may be modified, stripped, or falsified by consumer software or messaging platforms.",
        "Probabilistic AI detection scores represent statistical model outputs and must not be treated as a definitive authenticity verdict.",
        "Error Level Analysis (ELA) highlights compression differentials which naturally occur around high-contrast edges.",
        "Absence of Content Credentials (C2PA) is standard for consumer media and does not indicate alteration.",
        "This examination record is generated by an assistance tool for preliminary screening and does not replace accredited forensic procedures.",
    ]

    # Populate findings from actual analysis
    findings.append(f"Original file '{filename}' ({file_size_readable}) hashed with SHA-256.")

    if hashing_results and hashing_results.get("status") == "MATCH":
        findings.append("Integrity Check: MATCH confirmed against trusted reference digest.")
    elif hashing_results and hashing_results.get("status") == "MISMATCH":
        findings.append("Integrity Check: MISMATCH detected against reference digest.")

    if metadata_results.get("is_image"):
        dim = metadata_results.get("dimensions", "Unknown")
        fmt = metadata_results.get("format", "Unknown")
        findings.append(f"Image decoded successfully as {fmt} ({dim}).")
        exif_count = metadata_results.get("exif_count", 0)
        findings.append(f"Extracted {exif_count} readable EXIF tags.")
    else:
        findings.append("File could not be parsed as a standard image container.")

    for obs in metadata_results.get("observations", []):
        findings.append(f"Metadata Observation: {obs.get('title')} — {obs.get('interpretation')}")

    if ai_results:
        label = ai_results.get("assessment_label", "UNAVAILABLE")
        score = ai_results.get("raw_score")
        findings.append(f"Synthetic Media Assessment: {label} (Score: {score}).")

    if manipulation_results and manipulation_results.get("success"):
        findings.append(f"Error Level Analysis (ELA): Completed at {manipulation_results.get('quality_used')}% JPEG quality.")

    if provenance_results:
        findings.append(f"Content Provenance: {provenance_results.get('status')}.")

    record = {
        "report_id": examination_id,
        "created_at": now_utc,
        "system_version": "HashProof AI Forensic Suite v2.0",
        "examiner": {
            "name": examiner_name or "Digital Forensics Analyst",
            "case_reference": case_reference or "UNASSIGNED",
            "notes": examiner_notes or "",
        },
        "evidence": {
            "filename": filename,
            "size_bytes": file_size_bytes,
            "size_readable": file_size_readable,
            "sha256": file_hash,
            "detected_format": detected_format,
        },
        "integrity_analysis": hashing_results or {},
        "metadata_analysis": metadata_results,
        "manipulation_analysis": manipulation_results or {},
        "synthetic_media_assessment": ai_results or {},
        "provenance_analysis": provenance_results or {},
        "image_comparison": comparison_results or {},
        "findings": findings,
        "limitations": limitations,
        "disclaimer": (
            "NOTICE: HashProof AI is an automated digital evidence examination assistant. "
            "Observations and model scores contained herein are intended to guide qualified investigation "
            "and do not constitute legal conclusions or accredited expert testimony."
        ),
    }

    return record


def export_json(record: Dict[str, Any]) -> str:
    """Serialize the examination record to a pretty-printed UTF-8 JSON string."""
    return json.dumps(record, indent=2, ensure_ascii=False)


